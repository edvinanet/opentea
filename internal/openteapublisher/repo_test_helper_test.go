package openteapublisher

import (
	"path/filepath"
	"testing"
)

func newTestRepo(t *testing.T) *Repo {
	t.Helper()
	sqlDB, err := Open(filepath.Join(t.TempDir(), "test.db"))
	if err != nil {
		t.Fatalf("open test db: %v", err)
	}
	t.Cleanup(func() { _ = sqlDB.Close() })
	return New(sqlDB)
}
